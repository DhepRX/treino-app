const assert = require('node:assert/strict');
const { chromium, devices } = require('playwright');
const fs = require('node:fs/promises');
(async()=>{
  const b=await chromium.launch();
  try {
    const ctx=await b.newContext({...devices['iPhone 13'],serviceWorkers:'block',timezoneId:'America/Sao_Paulo',acceptDownloads:true});
    const p=await ctx.newPage(),erros=[];p.on('pageerror',e=>erros.push(e.message));
    await p.goto('http://127.0.0.1:8766/treino-app/');await p.click('[data-tab="A"]');
    const ler=()=>p.evaluate(()=>JSON.parse(localStorage.getItem('treino-renan-v1')));
    const inicial=await ler();
    assert.equal(inicial.cur,null,'Apenas abrir a tela não inicia um treino');
    const linhas=p.locator('#ex-a1 .sets .setrow:not(.head)');
    assert.deepEqual(await linhas.locator('.sn').allTextContents(),['A1','A2','1','2']);
    assert.equal(await p.locator('#ex-b1 [data-aquec-linha]').count(),0);
    assert.deepEqual(await linhas.evaluateAll(rs=>rs.map(r=>r.className)),Array(4).fill('setrow'));
    assert.equal(await p.locator('#ex-a1 .sets .restbtn').count(),4);
    assert.equal(await p.locator('#ex-a1 .sets [data-aquec-opcoes]').count(),0,'Ajustes ficam fora da lista de séries');
    await p.fill('#aquec-a1-0-kg','12,5');
    assert.equal(await p.inputValue('#aquec-a1-0-kg'),'12,5','Primeiro valor permanece quando começa o treino');
    assert.equal(await p.inputValue('#aquec-a1-1-kg'),'','A carga não é replicada para o outro aquecimento');
    await p.fill('#aquec-a1-0-reps','10');
    await p.click('#ex-a1 [data-aquec-opcoes] summary');
    await p.fill('#aquec-a1-0-rest','90');
    await p.click('[data-aquec-feito="a1:0"]');
    assert.equal(await p.textContent('[data-aquec-editar="a1:0"] span'),'12,5 kg × 10');
    assert.match(await p.textContent('#dockLabel'),/Descanso/);
    assert.match(await p.textContent('#dockClock'),/01:3\d|01:2\d/);
    assert.match(await p.textContent('#progresso'),/0 de/,'Aquecimento não aumenta trabalho feito');
    assert.equal((await ler()).cur.aquecimento.a1[0].kg,12.5);
    await p.click('#dockBtns [data-rest="30"]');
    assert.match(await p.textContent('#dockClock'),/0[12]:[0-5]\d/);
    await p.click('#dockBtns [data-rest="skip"]');
    assert.equal(await p.locator('[data-aquec-rest="a1:0"].on').count(),0);
    await p.reload();
    assert.equal(await p.textContent('[data-aquec-editar="a1:0"] span'),'12,5 kg × 10');
    await p.click('[data-aquec-editar="a1:0"]');
    assert.equal(await p.inputValue('#aquec-a1-0-kg'),'12,5');
    await p.fill('#aquec-a1-0-reps','11');
    await p.click('#ex-a1 [data-aquec-opcoes] summary');
    assert.equal(await p.inputValue('#aquec-a1-0-rest'),'90');
    assert.equal(await p.getAttribute('[data-aquec-feito="a1:0"]','aria-pressed'),'true');
    assert.equal((await ler()).cur.aquecimento.a1[0].reps,11);
    await p.click('[data-aquec-adicionar="a1"]');
    assert.deepEqual(await linhas.locator('.sn').allTextContents(),['A1','A2','A3','1','2']);
    await p.click('#ex-a1 [data-aquec-opcoes] summary');
    await p.click('[data-aquec-remover="a1:2"]');
    assert.equal(await p.locator('#ex-a1 [data-aquec-linha]').count(),2);
    await p.click('[data-aquec-adicionar="b1"]');
    assert.equal(await p.locator('#ex-b1 [data-aquec-linha]').count(),1);
    await p.click('#ex-b1 [data-aquec-opcoes] summary');
    await p.click('[data-aquec-remover="b1:0"]');
    assert.equal(await p.locator('#ex-b1 [data-aquec-linha]').count(),0);
    await p.click('[data-act="finish"]');await p.click('[data-act="finish"]');
    const soAquec=(await ler()).hist.find(h=>h.aquecimento);
    assert.equal(soAquec.interrompido,true);assert.deepEqual(soAquec.sets,{});
    assert.equal((await ler()).hist.length,inicial.hist.length+1);
    assert.match(await p.locator('#hist .aquec-history').first().textContent(),/12,5 kg × 11/);
    assert.doesNotMatch(await p.locator('#hist .aquec-history').first().textContent(),/aquecimento 2/i,'Linha inicial em branco não aparece como registro');
    await p.click('[data-view="progresso"]');assert.equal(await p.textContent('[data-volume-sete]'),'0');
    await p.reload();await p.click('[data-tab="A"]');
    assert.equal(await p.locator('[data-aquec-adicionar="a1"]').isEnabled(),true,'Só aquecer não bloqueia o treino do dia');
    await p.fill('#aquec-a1-0-kg','10');await p.fill('#aquec-a1-0-reps','8');
    await p.click('[data-aquec-feito="a1:0"]');
    await p.click('#ex-a1 [data-i="0"] [data-done]');
    await p.click('#ex-a1 .serie-notas summary');
    await p.selectOption('[data-serie-ex="a1"][data-serie-i="0"][data-serie-extra="rir"]','3');
    await p.selectOption('[data-serie-ex="a1"][data-serie-i="0"][data-serie-extra="unidade"]','halter');
    await p.fill('[data-serie-ex="a1"][data-serie-i="0"][data-serie-extra="nota"]','Execução de teste');
    await p.locator('[data-serie-ex="a1"][data-serie-i="0"][data-serie-extra="nota"]').dispatchEvent('change');
    await p.locator('[data-encerramento]').evaluate(el=>el.closest('details').open=true);
    await p.selectOption('[data-encerramento]','reduzido');
    await p.selectOption('[data-proximo-escolhido]','A');
    await p.click('[data-act="finish"]');await p.click('[data-act="finish"]');
    const feita=(await ler()).hist.find(h=>!h.interrompido&&h.aquecimento);
    assert.equal(feita.encerramento,'reduzido');assert.equal(feita.proximo,'A');
    assert.equal(feita.aquecimento.a1[0].kg,10);assert.equal(feita.sets.a1[0].rir,3);assert.equal(feita.sets.a1[0].unidade,'halter');
    await p.click('[data-view="progresso"]');assert.equal(await p.textContent('[data-volume-sete]'),'1');
    const [dl]=await Promise.all([p.waitForEvent('download'),p.click('#bkSave')]);
    const backup=JSON.parse(await fs.readFile(await dl.path(),'utf8'));
    assert.deepEqual(backup.hist.find(h=>h.id===feita.id).aquecimento,feita.aquecimento);
    await p.click('[data-view="treino"]');await p.click('[data-reabrir]');await p.click('[data-reabrir]');
    assert.equal((await ler()).cur.aquecimento.a1[0].kg,10);
    await p.reload();assert.equal((await ler()).cur.sets.a1[0].nota,'Execução de teste');
    assert.equal(await p.textContent('[data-aquec-editar="a1:0"] span'),'10 kg × 8');
    for (const width of [320,390]) {
      await p.setViewportSize({width,height:844});
      assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth),width);
    }
    assert.deepEqual(erros,[]);
    console.log('Aquecimento: duas linhas iniciais, adicionar/remover, edição, descanso/+30/pular, persistência, histórico, backup e exclusão do volume verificados.');
  } finally{await b.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
